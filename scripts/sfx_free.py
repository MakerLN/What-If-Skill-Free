#!/usr/bin/env python3
"""Synthesize simple sound effects from math (numpy only, no API, no samples).

Replaces the ElevenLabs sound-effect step of the What If pipeline. Because every
sound is generated by this code, the output has no third-party licence attached.
The effects are simple on purpose: they cover the common cartoon beats.

Usage:
  python sfx_free.py --list
  python sfx_free.py whoosh out/whoosh.wav [--dur 0.5] [--seed 1]
  python sfx_free.py --all studio/library/sfx_free/
"""
import argparse
import sys
import wave
from pathlib import Path

import numpy as np

SR = 44100
TAU = 2 * np.pi


def _t(n):
    return np.arange(n) / SR


def _noise(n, rng):
    return rng.standard_normal(n)


def _lowpass_sweep(x, f_start, f_end):
    """One-pole low-pass whose cutoff moves from f_start to f_end (arrays allowed)."""
    n = len(x)
    f = np.linspace(f_start, f_end, n) if np.isscalar(f_start) else f_start
    a = 1.0 - np.exp(-TAU * f / SR)
    y = np.empty(n)
    prev = 0.0
    for i in range(n):
        prev += a[i] * (x[i] - prev)
        y[i] = prev
    return y


def _bell(n):
    return np.sin(np.linspace(0, np.pi, n)) ** 2


def _decay(n, rate):
    return np.exp(-rate * np.linspace(0, 1, n))


def _fade(x, secs):
    k = min(int(secs * SR), len(x) // 2)
    if k > 0:
        ramp = np.linspace(0, 1, k)
        x[:k] *= ramp
        x[-k:] *= ramp[::-1]
    return x


# --- effects: each returns a float array in roughly [-1, 1] ------------------

def whoosh(dur, rng):
    n = int(dur * SR)
    f = np.concatenate([np.linspace(300, 4500, n // 2), np.linspace(4500, 300, n - n // 2)])
    return _lowpass_sweep(_noise(n, rng), f, None) * _bell(n)


def pop(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    freq = 250 + 450 * np.exp(-30 * t)
    phase = TAU * np.cumsum(freq) / SR
    return np.sin(phase) * _decay(n, 25)


def click(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    burst = _noise(n, rng) * _decay(n, 40)
    tick = np.sin(TAU * 1800 * t) * _decay(n, 60)
    return 0.6 * burst + 0.8 * tick


def thud(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    freq = 45 + 65 * np.exp(-14 * t)
    body = np.sin(TAU * np.cumsum(freq) / SR) * _decay(n, 7)
    knock = _lowpass_sweep(_noise(n, rng), 400, 80) * _decay(n, 18)
    return body + 0.4 * knock


def ding(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    out = np.zeros(n)
    for freq, amp, rate in [(1046.5, 1.0, 5), (2093.0, 0.4, 7), (3136.0, 0.2, 9)]:
        out += amp * np.sin(TAU * freq * t) * _decay(n, rate)
    return out


def rewind(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    freq = 300 * (2500 / 300) ** np.linspace(0, 1, n)
    tone = np.sin(TAU * np.cumsum(freq) / SR)
    trem = 0.6 + 0.4 * np.sin(TAU * 18 * t)
    hiss = _lowpass_sweep(_noise(n, rng), 800, 6000)
    env = np.linspace(0.1, 1, n) ** 1.5
    return (0.6 * tone * trem + 0.5 * hiss) * env


def riser(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    hiss = _lowpass_sweep(_noise(n, rng), 200, 6000)
    tone = np.sin(TAU * np.cumsum(200 + 600 * np.linspace(0, 1, n) ** 2) / SR)
    env = np.linspace(0, 1, n) ** 2
    return (0.7 * hiss + 0.4 * tone) * env


def boing(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    freq = 220 * (1 + 0.6 * np.exp(-4 * t) * np.cos(TAU * 9 * t))
    return np.sin(TAU * np.cumsum(freq) / SR) * _decay(n, 4)


def glitch(dur, rng):
    n = int(dur * SR)
    out = np.zeros(n)
    i = 0
    while i < n:
        seg = int(rng.uniform(0.008, 0.03) * SR)
        seg = min(seg, n - i)
        kind = rng.integers(0, 3)
        if kind == 0:
            out[i:i + seg] = _noise(seg, rng) * 0.6
        elif kind == 1:
            f = rng.uniform(200, 3000)
            out[i:i + seg] = np.sign(np.sin(TAU * f * _t(seg))) * 0.4
        i += seg + int(rng.uniform(0, 0.02) * SR)
    return out


def ambience_room(dur, rng):
    n = int(dur * SR)
    brown = np.cumsum(_noise(n, rng))
    brown -= np.convolve(brown, np.ones(SR // 4) / (SR // 4), mode="same")
    brown = _lowpass_sweep(brown, 600, 600)
    return _fade(brown, 0.5)


def pad(dur, rng):
    n = int(dur * SR)
    t = _t(n)
    out = np.zeros(n)
    for freq in (110.0, 130.81, 164.81, 220.0):  # A minor
        for detune in (-0.3, 0.0, 0.3):
            out += np.sin(TAU * (freq + detune) * t + rng.uniform(0, TAU))
    out *= 0.75 + 0.25 * np.sin(TAU * 0.12 * t)
    return _fade(out, 2.0)


# name -> (function, default duration s, peak level)
EFFECTS = {
    "whoosh": (whoosh, 0.5, 0.8),
    "pop": (pop, 0.15, 0.8),
    "click": (click, 0.05, 0.7),
    "thud": (thud, 0.5, 0.9),
    "ding": (ding, 1.0, 0.7),
    "rewind": (rewind, 0.9, 0.8),
    "riser": (riser, 1.5, 0.8),
    "boing": (boing, 0.6, 0.8),
    "glitch": (glitch, 0.4, 0.7),
    "ambience_room": (ambience_room, 10.0, 0.25),
    "pad": (pad, 20.0, 0.3),
}


def render(name, dur=None, seed=0):
    fn, default_dur, peak = EFFECTS[name]
    rng = np.random.default_rng(seed)
    x = fn(dur or default_dur, rng).astype(np.float64)
    m = np.max(np.abs(x))
    if m > 0:
        x = x / m * peak
    return x


def write_wav(path, x):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", nargs="?", help="effect name (see --list)")
    ap.add_argument("out", nargs="?", help="output .wav path")
    ap.add_argument("--dur", type=float, help="duration in seconds")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--all", metavar="OUTDIR", help="render every effect into OUTDIR")
    args = ap.parse_args()

    if args.list:
        for name, (_fn, dur, _peak) in EFFECTS.items():
            print(f"{name:14s} default {dur:g}s")
        return 0
    if args.all:
        for name in EFFECTS:
            write_wav(Path(args.all) / f"{name}.wav", render(name, seed=args.seed))
            print("wrote", Path(args.all) / f"{name}.wav")
        return 0
    if not (args.name and args.out):
        ap.error("give NAME and OUT, or use --list / --all")
    if args.name not in EFFECTS:
        ap.error(f"unknown effect '{args.name}'. Use --list.")
    write_wav(args.out, render(args.name, args.dur, args.seed))
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
